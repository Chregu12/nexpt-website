#!/usr/bin/env python3
"""Generate static Ghost metadata and public AI text exports from Nexpt's pages."""
import html
import importlib.util
import json
import re
import sys
from pathlib import Path

spec = importlib.util.spec_from_file_location('preview', Path(__file__).with_name('preview-nexpt-theme.py'))
preview = importlib.util.module_from_spec(spec)
spec.loader.exec_module(preview)
config = json.loads((preview.THEME / 'seo.json').read_text())
site = config['site_url']
organization = site + '/#organization'
website = site + '/#website'
check = '--check' in sys.argv


def write(path, content):
    if check:
        assert path.is_file() and path.read_text() == content, f'Stale SEO output: {path}; run python3 scripts/build-nexpt-seo.py'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


for name, page in config['pages'].items():
    source = (preview.THEME / (name + '.hbs')).read_text()
    title = re.search(r'{{#contentFor "pageTitle"}}(.*?){{/contentFor}}', source, re.S)[1].strip()
    url = site + preview.page_path(name)
    image_name = page.get('image', 'nexpt-icon.png')
    image = site + '/assets/' + image_name
    width, height = (1280, 720) if page.get('image') else (256, 256)
    image_alt = 'Raphael und Christian Heusser, die Gründer von Nexpt' if page.get('image') else 'Nexpt'
    breadcrumbs = [{'@type': 'ListItem', 'position': 1, 'name': 'Nexpt', 'item': site + '/work/'}]
    if name != 'work':
        breadcrumbs.append({'@type': 'ListItem', 'position': 2, 'name': page['label'], 'item': url})
    graph = [
        {'@type': 'Organization', '@id': organization, 'name': config['name'], 'url': site + '/work/',
         'logo': {'@type': 'ImageObject', 'url': site + '/assets/nexpt-icon.png', 'width': 256, 'height': 256},
         'founder': [{'@type': 'Person', 'name': person, 'url': site + '/work/wer-wir-sind/'}
                     for person in ['Raphael Heusser', 'Christian Heusser']]},
        {'@type': 'WebSite', '@id': website, 'name': config['name'], 'url': site + '/work/',
         'description': config['description'], 'inLanguage': 'de-CH', 'publisher': {'@id': organization}},
        {'@type': page.get('page_type', 'WebPage'), '@id': url + '#webpage', 'url': url, 'name': title,
         'description': page['description'], 'inLanguage': 'de-CH', 'isPartOf': {'@id': website},
         'about': {'@id': organization}, 'breadcrumb': {'@id': url + '#breadcrumb'}},
        {'@type': 'BreadcrumbList', '@id': url + '#breadcrumb', 'itemListElement': breadcrumbs}
    ]
    if page.get('application'):
        app = {'@type': 'SoftwareApplication', '@id': url + '#application', 'name': page['application'],
               'url': url, 'description': page['description'], 'applicationCategory': 'BusinessApplication',
               'operatingSystem': 'Web', 'publisher': {'@id': organization}}
        graph.append(app)
        graph[2]['mainEntity'] = {'@id': app['@id']}
    robots = 'noindex,follow' if page.get('noindex') else 'index,follow,max-image-preview:large,max-snippet:-1,max-video-preview:-1'
    entries = [('name', 'description', page['description']), ('name', 'robots', robots),
               ('property', 'og:site_name', config['name']), ('property', 'og:locale', 'de_CH'),
               ('property', 'og:type', 'website'), ('property', 'og:title', title),
               ('property', 'og:description', page['description']), ('property', 'og:url', url),
               ('property', 'og:image', image), ('property', 'og:image:width', str(width)),
               ('property', 'og:image:height', str(height)), ('property', 'og:image:alt', image_alt),
               ('name', 'twitter:card', 'summary_large_image' if page.get('image') else 'summary'),
               ('name', 'twitter:title', title), ('name', 'twitter:description', page['description']),
               ('name', 'twitter:image', image), ('name', 'twitter:image:alt', image_alt)]
    head = ['{{! Generated by scripts/build-nexpt-seo.py. Edit seo.json and pageTitle in the page template. }}',
            '<title>' + html.escape(title) + '</title>']
    head += [f'<meta {kind}="{key}" content="{html.escape(value, quote=True)}">' for kind, key, value in entries]
    head += [f'<link rel="canonical" href="{html.escape(url, quote=True)}">',
             '<link rel="icon" type="image/png" href="{{asset \'nexpt-icon.png\'}}">',
             '<meta name="referrer" content="no-referrer-when-downgrade">']
    if not page.get('noindex'):
        # Escape script delimiters without changing JSON values for structured-data consumers.
        schema = json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False, indent=2)
        for char, escaped in [('<', '\\u003c'), ('>', '\\u003e'), ('&', '\\u0026'), ('\u2028', '\\u2028'), ('\u2029', '\\u2029')]:
            schema = schema.replace(char, escaped)
        head += ['<script type="application/ld+json">', schema, '</script>']
    write(preview.THEME / 'partials' / 'seo' / (name + '.hbs'), '\n'.join(head) + '\n')

intro = ['# Nexpt – Arbeit, Menschen und Wissen', '', '> ' + config['description'], '',
         'Die Website stellt Nexpt Work, Nexpt HR und Nexpt Outline anhand illustrativer Produktvorschauen vor. '
         'Aktuellen Funktionsumfang, Zugang und Anbindungen klären die Gründer im persönlichen Gespräch. '
         'Verfügbarkeit und Einrichtung von Verzeichnisanbindungen hängen von der jeweiligen Umgebung ab.', '']
index = intro + ['## Produkt- und Themenseiten', '']
full = intro.copy()
for name in preview.PAGES:
    page = config['pages'][name]
    url = site + preview.page_path(name)
    index.append(f'- [{page["label"]}]({url}): {page["description"]}')
    parser = preview.MainText()
    parser.feed(preview.render((preview.THEME / (name + '.hbs')).read_text(), site))
    full += ['## ' + page['label'], '', 'Quelle: ' + url, '', ' '.join(' '.join(parser.parts).split()), '']
index += ['', '## Weitere Informationen', '',
          f'- [Vollständige öffentliche Seitentexte]({site}/llms-full.txt)',
          f'- [Sitemap]({site}/sitemap.xml)', '']
write(preview.THEME / 'assets' / 'nexpt-llms.txt', '\n'.join(index))
write(preview.THEME / 'assets' / 'nexpt-llms-full.txt', '\n'.join(full))
print(('PASS: generated SEO and AI text exports match' if check else 'Updated SEO and AI text exports for'), len(config['pages']), 'templates.')
